type GenerateOptions struct {
	PackageName        string
	IncludeMain        bool
	TracePath          string // Explicit standalone execution trace destination.
	IncludeDiagnostics bool   // Include source-aware executionError for custom entry points.
}

func GenerateGo(g *Graph) (string, error) {
	return GenerateGoWithOptions(g, GenerateOptions{PackageName: "main", IncludeMain: true})
}

func GenerateGoWithOptions(g *Graph, options GenerateOptions) (string, error) {
	if g == nil {
		return "", fmt.Errorf("cannot generate a nil graph")
	}
	if options.TracePath != "" && !options.IncludeMain {
		return "", fmt.Errorf("a trace destination requires standalone generation")
	}
	if options.PackageName == "" {
		options.PackageName = "main"
	}
	if !gotoken.IsIdentifier(options.PackageName) || options.PackageName == "_" {
		return "", fmt.Errorf("invalid Go package name %q", options.PackageName)
	}
	if options.IncludeMain && options.PackageName != "main" {
		return "", fmt.Errorf("standalone generation requires package main; use library mode (--no-main) for package %s", options.PackageName)
	}
	var b strings.Builder
	b.WriteString("// Code generated by lipc; DO NOT EDIT.\n")
	fmt.Fprintf(&b, "// LIP %s\n", runtime.Version)
	fmt.Fprintf(&b, "package %s\n\n", options.PackageName)
	b.WriteString("import (\n\t\"context\"\n")
	// Generated input checks, strict CLI parsing, instances and optional mains use fmt.
	b.WriteString("\t\"fmt\"\n")
	if options.IncludeMain {
		b.WriteString("\t\"os\"\n")
		if !hasHostOrGoDependency(g) {
			b.WriteString("\t\"os/signal\"\n\t\"syscall\"\n")
			if options.TracePath != "" {
				b.WriteString("\t\"path/filepath\"\n")
			}
		}
	}
	b.WriteString("\n\t\"lipalpha/runtime\"\n)\n\n")
	b.WriteString("type Dependency struct { Kind string; Spec string; Alias string }\n\nfunc RequiredDependencies() []Dependency { return []Dependency{")
	for _, dependency := range g.Dependencies {
		fmt.Fprintf(&b, "{Kind: %s, Spec: %s", quote(dependency.Kind), quote(dependency.Spec))
		if dependency.Alias != "" {
			fmt.Fprintf(&b, ", Alias: %s", quote(dependency.Alias))
		}
		b.WriteString("},")
	}
	b.WriteString("} }\n\n")
	if options.IncludeMain {
		b.WriteString("func parseCLIInputs(args []string) (map[string]runtime.Value, error) {\n")
		b.WriteString("\tinputs, err := runtime.ParseCLIInputs(args, []runtime.Input{")
		for _, param := range g.Params {
			fmt.Fprintf(&b, "{Name: %s, Type: %s},", quote(param), quote(gParamType(g, param)))
		}
		b.WriteString("})\n")
		b.WriteString("\tif err != nil { return nil, fmt.Errorf(\"%w\\nusage: %s")
		for _, param := range g.Params {
			fmt.Fprintf(&b, " <%s:%s>", param, gParamType(g, param))
		}
		b.WriteString("\", err, os.Args[0]) }; return inputs, nil\n}\n\n")
	}
	for _, fn := range g.Functions {
		code, err := emitFunction(fn)
		if err != nil {
			return "", err
		}
		b.WriteString(code)
		b.WriteString("\n")
	}
	if err := emitGraphFunction(g, "buildGraph", &b); err != nil {
		return "", err
	}
	b.WriteString("func checkInputUpdates(inputs map[string]runtime.Value) error {\n\tfor name, value := range inputs {\n\t\t_ = value\n\t\tswitch name {\n")
	for _, param := range g.Params {
		fmt.Fprintf(&b, "\t\tcase %s: if err := runtime.CheckType(value, %s); err != nil { return fmt.Errorf(\"input %s: %%w\", err) }\n", quote(param), quote(gParamType(g, param)), param)
	}
	b.WriteString("\t\tdefault: return fmt.Errorf(\"unknown flow input %q\", name)\n\t\t}\n\t}\n\treturn nil\n}\n\n")
	b.WriteString("func checkInputs(inputs map[string]runtime.Value) error {\n")
	for _, param := range g.Params {
		fmt.Fprintf(&b, "\tif _, ok := inputs[%s]; !ok { return fmt.Errorf(\"missing flow input %s\") }\n", quote(param), param)
	}
	b.WriteString("\treturn checkInputUpdates(inputs)\n}\n\n")
	b.WriteString("func checkHost(host runtime.Host) error {\n")
	for _, operation := range requiredHostOperations(g) {
		fmt.Fprintf(&b, "\tif err := host.RequireOperation(%s); err != nil { return err }\n", quote(operation))
	}
	b.WriteString("\treturn nil\n}\n\n")
	b.WriteString("type Instance struct { engine *runtime.Instance }\n\n")
	b.WriteString("func NewInstance(host runtime.Host, inputs map[string]runtime.Value) (*Instance, error) { if err := checkInputs(inputs); err != nil { return nil, err }; if err := checkHost(host); err != nil { return nil, err }; graph := buildGraph(host); return &Instance{engine: graph.NewInstance(host, inputs)}, nil }\n\n")
	b.WriteString("func (i *Instance) Tick(ctx context.Context, inputs map[string]runtime.Value) (runtime.Value, []runtime.TraceEvent, error) { if i == nil || i.engine == nil { return nil, nil, fmt.Errorf(\"nil flow instance\") }; if err := checkInputUpdates(inputs); err != nil { return nil, nil, err }; return i.engine.Tick(ctx, inputs) }\n\n")
	b.WriteString("func (i *Instance) SetState(name string, value runtime.Value) error { if i == nil || i.engine == nil { return fmt.Errorf(\"nil flow instance\") }; return i.engine.SetState(name, value) }\n\n")
	b.WriteString("func (i *Instance) State(name string) (runtime.Value, bool) { if i == nil || i.engine == nil { return nil, false }; return i.engine.State(name) }\n\n")
	b.WriteString("func (i *Instance) TickCount() uint64 { if i == nil || i.engine == nil { return 0 }; return i.engine.TickCount() }\n\n")
	b.WriteString("func Run(ctx context.Context, host runtime.Host, inputs map[string]runtime.Value) (runtime.Value, []runtime.TraceEvent, error) { if err := checkInputs(inputs); err != nil { return nil, nil, err }; if err := checkHost(host); err != nil { return nil, nil, err }; return buildGraph(host).RunAuto(ctx, host, inputs) }\n\n")
	b.WriteString("func RunSequential(ctx context.Context, host runtime.Host, inputs map[string]runtime.Value) (runtime.Value, []runtime.TraceEvent, error) { if err := checkInputs(inputs); err != nil { return nil, nil, err }; if err := checkHost(host); err != nil { return nil, nil, err }; return buildGraph(host).Run(ctx, inputs) }\n\n")
	b.WriteString("func RunParallel(ctx context.Context, host runtime.Host, inputs map[string]runtime.Value, limit int) (runtime.Value, []runtime.TraceEvent, error) { if err := checkInputs(inputs); err != nil { return nil, nil, err }; if err := checkHost(host); err != nil { return nil, nil, err }; return buildGraph(host).RunParallel(ctx, host, inputs, limit) }\n")
	if options.IncludeMain || options.IncludeDiagnostics {
		b.WriteString("\nfunc executionError(err error, trace []runtime.TraceEvent) error {\n\tmessage, context := err.Error(), \"\"\n\tfor _, event := range trace {\n\t\tif event.Status != runtime.Error { continue }; switch event.Node {\n")
		lines := strings.Split(g.Source, "\n")
		for _, node := range g.Nodes {
			path := g.SourceName
			if path == "" {
				path = "<input>"
			}
			d := Diagnostic{Line: node.Pos.Line, Column: node.Pos.Column}
			if d.Line > 0 && d.Line <= len(lines) {
				d.SourceLine = strings.TrimSuffix(lines[d.Line-1], "\r")
			}
			prefix := fmt.Sprintf("%s:%d:%d: ", path, d.Line, d.Column)
			fmt.Fprintf(&b, "\t\tcase %s: message = %s + event.Reason; context = %s\n", quote(node.Name), quote(prefix), quote(diagnosticContext(d)))
		}
		b.WriteString("\t\t}; break\n\t}\n")
		b.WriteString("\tif line, column, found := runtime.SourcePosition(err); found { switch fmt.Sprintf(\"%d:%d\", line, column) {\n")
		var sourceContexts func(*Graph)
		seenPositions := map[string]bool{}
		sourceContexts = func(graph *Graph) {
			for _, node := range graph.Nodes {
				if node.For == nil {
					continue
				}
				for _, inner := range node.For.Body.Nodes {
					position := fmt.Sprintf("%d:%d", inner.Pos.Line, inner.Pos.Column)
					if seenPositions[position] {
						continue
					}
					seenPositions[position] = true
					d := Diagnostic{Line: inner.Pos.Line, Column: inner.Pos.Column}
					if d.Line > 0 && d.Line <= len(lines) {
						d.SourceLine = strings.TrimSuffix(lines[d.Line-1], "\r")
					}
					path := g.SourceName
					if path == "" {
						path = "<input>"
					}
					fmt.Fprintf(&b, "\tcase %s: message = %s + err.Error(); context = %s\n", quote(position), quote(fmt.Sprintf("%s:%s: ", path, position)), quote(diagnosticContext(d)))
				}
				sourceContexts(node.For.Body)
			}
		}
		sourceContexts(g)
		b.WriteString("\t} }\n\tif hint := runtime.ExecutionHint(err); hint != \"\" { context += \"\\n  hint: \" + hint }; return fmt.Errorf(\"%s%s\", message, context)\n}\n")
	}
	if options.IncludeMain {
		b.WriteString("\nfunc main() { os.Exit(runMain()) }\n\nfunc runMain() int {\n\tinputs, err := parseCLIInputs(os.Args[1:])\n\tif err != nil { fmt.Fprintln(os.Stderr, err); return 2 }\n\t_ = inputs\n")
		if hasHostOrGoDependency(g) {
			b.WriteString("\tfmt.Fprintln(os.Stderr, \"host/go dependencies require a Go host program; use library mode\")\n\t\treturn 1\n")
		} else {
			b.WriteString("\tctx, stop := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)\n\tdefer stop()\n\thost := runtime.DefaultHost()\n")
			if hasPythonDependency(g) {
				// A standalone program opts into the Python process only through an
				// explicit import python declaration. Library mode leaves ownership
				// to its Go host so it can choose the interpreter and policy.
				b.WriteString("\tworker, err := runtime.NewPythonWorker(ctx, runtime.PythonWorkerConfig{})\n\tif err != nil { fmt.Fprintln(os.Stderr, \"python worker:\", err); return 1 }\n\tdefer worker.Close()\n\thost = runtime.NewPythonHost(worker)\n")
			}
			b.WriteString("\tvalue, trace, err := Run(ctx, host, inputs)\n")
			if options.TracePath != "" {
				fmt.Fprintf(&b, "\ttraceErr := os.MkdirAll(filepath.Dir(%s), 0o755)\n", quote(options.TracePath))
				fmt.Fprintf(&b, "\tif traceErr == nil { var traceFile *os.File; traceFile, traceErr = os.Create(%s); if traceErr == nil { traceErr = runtime.WriteTrace(traceFile, trace, err); closeErr := traceFile.Close(); if traceErr == nil { traceErr = closeErr } } }\n", quote(options.TracePath))
				b.WriteString("\tif traceErr != nil { if err != nil { fmt.Fprintln(os.Stderr, \"error:\", err) }; fmt.Fprintln(os.Stderr, \"trace:\", traceErr); return 1 }\n")
			}
			b.WriteString("\tif err != nil { fmt.Fprintln(os.Stderr, \"error:\", executionError(err, trace)); return 1 }\n")
			if g.ReturnType == "void" {
				b.WriteString("\t_ = value\n\treturn 0\n")
			} else {
				b.WriteString("\toutput, err := runtime.FormatValue(value); if err != nil { fmt.Fprintln(os.Stderr, err); return 1 }; fmt.Println(output)\n\treturn 0\n")
			}
		}
		b.WriteString("}\n")
	}
	return b.String(), nil
}

func hasPythonDependency(g *Graph) bool {
	for _, node := range g.Nodes {
		if firstPythonCall(node.Expr) != nil {
			return true
		}
		if node.FeedbackAttempts > 0 {
			call := node.Expr.(*ast.CallExpr)
			if firstPythonCall(feedbackOperation(call, 1)) != nil || firstPythonCall(feedbackOperation(call, 2)) != nil {
				return true
			}
		}
		if node.For != nil && hasPythonDependency(node.For.Body) {
			return true
		}
	}
	return false
}

func hasHostOrGoDependency(g *Graph) bool {
	return len(requiredHostOperations(g)) > 0
}

// RequiresPython reports whether execution can use Python, including attributes,
// feedback callbacks and nested loops. Unused import declarations do not count.
func (g *Graph) RequiresPython() bool { return hasPythonDependency(g) }

// RequiresHost reports whether execution needs explicitly registered Host/Go
// adapters. Core operations supplied by DefaultHost do not require adapters.
func (g *Graph) RequiresHost() bool { return hasHostOrGoDependency(g) }

func emitExpr(expr ast.Expr) (string, error) {
	ident := func(name string) string { return fmt.Sprintf("values[%s]", quote(name)) }
	emitter := newValueEmitter(ident, "\t\t")
	return emitResultExpr(expr, emitter)
}

func emitMapElement(comp *ast.ComprehensionExpr) (string, error) {
	ident := func(name string) string {
		if name == comp.Variable {
			return "item"
		}
		return fmt.Sprintf("values[%s]", quote(name))
	}
	emitter := newValueEmitter(ident, "\t\t\t")
	return emitResultExpr(comp.Element, emitter)
}

func emitResultExpr(expr ast.Expr, emitter *valueEmitter) (string, error) {
	if call, ok := expr.(*ast.CallExpr); ok && !call.PythonAttribute && (externalCall(call) || !pureBuiltinName(call.Name) && !randomBuiltinName(call.Name)) {
		args := make([]string, len(call.Args))
		for i, arg := range call.Args {
			value, err := emitter.value(arg)
			if err != nil {
				return "", err
			}
			args[i] = value
		}
		emitter.line("return host.Call(ctx, %s, []runtime.Value{%s})", quote(dispatchName(call)), strings.Join(args, ", "))
		return emitter.code(), nil
	}
	value, err := emitter.value(expr)
	if err != nil {
		return "", err
	}
	emitter.line("return runtime.Ready(%s)", value)
	return emitter.code(), nil
}

func dispatchName(call *ast.CallExpr) string {
	if call.Local {
		return "__lip_fn_" + call.Name
	}
	return call.Name
}

type valueEmitter struct {
	lines  *[]string
	next   *int
	indent string
	ident  func(string) string
}

func newValueEmitter(ident func(string) string, indent string) *valueEmitter {
	lines := []string{}
	next := 0
	return &valueEmitter{lines: &lines, next: &next, indent: indent, ident: ident}
}

func (e *valueEmitter) child(indent string) *valueEmitter {
	return &valueEmitter{lines: e.lines, next: e.next, indent: indent, ident: e.ident}
}

func (e *valueEmitter) line(format string, args ...any) {
	*e.lines = append(*e.lines, e.indent+fmt.Sprintf(format, args...))
}

func (e *valueEmitter) temp() string {
	name := fmt.Sprintf("value%d", *e.next)
	*e.next = *e.next + 1
	return name
}

func (e *valueEmitter) code() string { return strings.Join(*e.lines, "\n") }

func (e *valueEmitter) value(expr ast.Expr) (string, error) {
	switch x := expr.(type) {
	case *ast.LiteralExpr:
		return literal(x.Value), nil
	case *ast.IdentExpr:
		return e.ident(x.Name), nil
	case *ast.CallExpr:
		if x.PythonAttribute {
			value := e.temp()
			e.line("%s, err := runtime.ResolveValue(ctx, host.Call(ctx, \"python.getattr\", []runtime.Value{%s}))", value, quote(x.Name))
			e.line("if err != nil { return runtime.Failed(err) }")
			return value, nil
		}
		if externalCall(x) {
			args := make([]string, len(x.Args))
			for index, arg := range x.Args {
				value, err := e.value(arg)
				if err != nil {
					return "", err
				}
				args[index] = value
			}
			value := e.temp()
			e.line("%s, err := runtime.ResolveValue(ctx, host.Call(ctx, %s, []runtime.Value{%s}))", value, quote(x.Name), strings.Join(args, ", "))
			e.line("if err != nil { return runtime.Failed(err) }")
			return value, nil
		}
		if _, ok := stringops.Lookup(x.Name); ok && !x.Python {
			args := make([]string, len(x.Args))
			for index, arg := range x.Args {
				value, err := e.value(arg)
				if err != nil {
					return "", err
				}
				args[index] = value
			}
			value := e.temp()
			e.line("%s, err := runtime.StringCall(ctx, %s, []runtime.Value{%s})", value, quote(x.Name), strings.Join(args, ", "))
			e.line("if err != nil { return runtime.Failed(err) }")
			return value, nil
		}
		if spec, ok := listops.Lookup(x.Name); ok && !x.Python {
			args := []string{}
			reducer := "nil"
			callbackSlot := callbackIndex(x)
			for index, arg := range x.Args {
				if index == callbackSlot {
					var err error
					reducer, err = e.callback(arg)
					if err != nil {
						return "", err
					}
				} else {
					value, err := e.value(arg)
					if err != nil {
						return "", err
					}
					args = append(args, value)
				}
			}
			value := e.temp()
			listName := spec.Name
			if sortComparatorCall(x) {
				listName = "list.sort_with"
			}
			e.line("%s, err := runtime.ListCall(ctx, %s, []runtime.Value{%s}, %s)", value, quote(listName), strings.Join(args, ", "), reducer)
			e.line("if err != nil { return runtime.Failed(err) }")
			return value, nil
		}
		if x.Name == "fold" {
			if len(x.Args) != 3 {
				return "", fmt.Errorf("fold expects 3 arguments")
			}
			source, err := e.value(x.Args[0])
			if err != nil {
				return "", err
			}
			seed, err := e.value(x.Args[1])
			if err != nil {
				return "", err
			}
			reducer, err := e.callback(x.Args[2])
			if err != nil {
				return "", err
			}
			value := e.temp()
			e.line("%s, err := runtime.Fold(ctx, %s, %s, %s)", value, source, seed, reducer)
			e.line("if err != nil { return runtime.Failed(err) }")
			return value, nil
		}
		args := make([]string, len(x.Args))
		for i, arg := range x.Args {
			value, err := e.value(arg)
			if err != nil {
				return "", err
			}
			args[i] = value
		}
		if x.Name == "str" {
			if len(args) != 1 {
				return "", fmt.Errorf("str expects 1 argument")
			}
			return "runtime.StringValue(" + args[0] + ")", nil
		}
		if x.Name == "isEmpty" || x.Name == "isNotEmpty" || x.Name == "is_empty" || x.Name == "is_not_empty" || randomBuiltinName(x.Name) {
			value := e.temp()
			if randomBuiltinName(x.Name) {
				e.line("%s, err := runtime.RandomCall(ctx, %s, []runtime.Value{%s})", value, quote(x.Name), strings.Join(args, ", "))
			} else if x.Name == "isEmpty" || x.Name == "is_empty" {
				e.line("%s, err := runtime.IsEmpty(%s)", value, args[0])
			} else {
				e.line("%s, err := runtime.IsNotEmpty(%s)", value, args[0])
			}
			e.line("if err != nil { return runtime.Failed(err) }")
			return value, nil
		}
		if x.Name == "len" || x.Name == "range" || x.Name == "fail" {
			value := e.temp()
			if x.Name == "fail" {
				if len(args) != 1 {
					return "", fmt.Errorf("fail expects 1 argument")
				}
				e.line("%s, err := runtime.Fail(ctx, %s)", value, args[0])
			} else if x.Name == "len" {
				if len(args) != 1 {
					return "", fmt.Errorf("len expects 1 argument")
				}
				e.line("%s, err := runtime.Length(%s)", value, args[0])
			} else {
				e.line("%s, err := runtime.Range(ctx, []runtime.Value{%s})", value, strings.Join(args, ", "))
			}
			e.line("if err != nil { return runtime.Failed(err) }")
			return value, nil
		}
		value := e.temp()
		e.line("%s, err := runtime.ResolveValue(ctx, host.Call(ctx, %s, []runtime.Value{%s}))", value, quote(dispatchName(x)), strings.Join(args, ", "))
		e.line("if err != nil { return runtime.Failed(err) }")
		return value, nil
	case *ast.UnaryExpr:
		operand, err := e.value(x.Operand)
		if err != nil {
			return "", err
		}
		value := e.temp()
		e.line("%s, err := runtime.Bool(%s)", value, operand)
		e.line("if err != nil { return runtime.Failed(err) }")
		return "runtime.Value(!" + value + ")", nil
	case *ast.ObjectExpr:
		// Materialize fields one by one: str and nested literals also need
		// evaluation here, before later field expressions can fail.
		object := e.temp()
		e.line("%s := map[string]runtime.Value{}", object)
		for _, field := range x.Fields {
			value, err := e.value(field.Value)
			if err != nil {
				return "", err
			}
			e.line("%s[%s] = %s", object, quote(field.Name), value)
		}
		return object, nil
	case *ast.BinaryExpr:
		left, err := e.value(x.Left)
		if err != nil {
			return "", err
		}
		if x.Op == "&&" || x.Op == "||" {
			value, condition := e.temp(), e.temp()
			e.line("var %s runtime.Value", value)
			e.line("%s, err := runtime.Bool(%s)", condition, left)
			e.line("if err != nil { return runtime.Failed(err) }")
			e.line("%s = %s", value, condition)
			guard := condition
			if x.Op == "||" {
				guard = "!" + condition
			}
			e.line("if %s {", guard)
			branch := e.child(e.indent + "\t")
			right, err := branch.value(x.Right)
			if err != nil {
				return "", err
			}
			boolean := e.temp()
			branch.line("%s, err := runtime.Bool(%s)", boolean, right)
			branch.line("if err != nil { return runtime.Failed(err) }")
			branch.line("%s = %s", value, boolean)
			e.line("}")
			return value, nil
		}
		right, err := e.value(x.Right)
		if err != nil {
			return "", err
		}
		value := e.temp()
		e.line("%s, err := runtime.Binary(%s, %s, %s)", value, quote(x.Op), left, right)
		e.line("if err != nil { return runtime.Failed(err) }")
		return value, nil
	case *ast.ListExpr:
		items := make([]string, len(x.Items))
		for i, item := range x.Items {
			value, err := e.value(item)
			if err != nil {
				return "", err
			}
			items[i] = value
		}
		return "[]runtime.Value{" + strings.Join(items, ", ") + "}", nil
	case *ast.ComprehensionExpr:
		// Keep composed maps inside the current expression: lifting them into
		// eager graph nodes would break short-circuiting and evaluation order.
		source, err := e.value(x.Source)
		if err != nil {
			return "", err
		}
		value, item := e.temp(), e.temp()
		e.line("%s, err := runtime.MapValues(ctx, %s, func(ctx context.Context, %s runtime.Value) runtime.Result {", value, source, item)
		body := e.child(e.indent + "\t")
		body.ident = func(name string) string {
			if name == x.Variable {
				return item
			}
			return e.ident(name)
		}
		if _, err := emitResultExpr(x.Element, body); err != nil {
			return "", err
		}
		e.line("})")
		e.line("if err != nil { return runtime.Failed(err) }")
		return value, nil
	case *ast.FieldExpr:
		object, err := e.value(x.Object)
		if err != nil {
			return "", err
		}
		value := e.temp()
		e.line("%s, err := runtime.Field(%s, %s)", value, object, quote(x.Name))
		e.line("if err != nil { return runtime.Failed(err) }")
		return value, nil
	case *ast.IndexExpr:
		object, err := e.value(x.Object)
		if err != nil {
			return "", err
		}
		index, err := e.value(x.Index)
		if err != nil {
			return "", err
		}
		value := e.temp()
		e.line("%s, err := runtime.Index(%s, %s)", value, object, index)
		e.line("if err != nil { return runtime.Failed(err) }")
		return value, nil
	case *ast.IfExpr:
		cond, err := e.value(x.Cond)
		if err != nil {
			return "", err
		}
		value := e.temp()
		e.line("var %s runtime.Value", value)
		condition := e.temp()
		e.line("%s, err := runtime.Bool(%s)", condition, cond)
		e.line("if err != nil { return runtime.Failed(err) }")
		e.line("if %s {", condition)
		thenEmitter := e.child(e.indent + "\t")
		thenValue, err := thenEmitter.value(x.Then)
		if err != nil {
			return "", err
		}
		thenEmitter.line("%s = %s", value, thenValue)
		e.line("} else {")
		elseEmitter := e.child(e.indent + "\t")
		elseValue, err := elseEmitter.value(x.Else)
		if err != nil {
			return "", err
		}
		elseEmitter.line("%s = %s", value, elseValue)
		e.line("}")
		return value, nil
	case *ast.MatchExpr:
		return e.matchValue(x)
	default:
		return "", fmt.Errorf("unsupported expression %T", expr)
	}
}

func (e *valueEmitter) callback(expr ast.Expr) (string, error) {
	if named, ok := expr.(*ast.IdentExpr); ok {
		// Collection reducers invoke their Op directly. Route named local
		// callbacks through Host.Call so a tail call at the callback's return
		// position is consumed by the trampoline instead of escaping as an
		// internal runtime value.
		callback := e.temp()
		args := e.temp()
		e.line("%s := runtime.Op(func(ctx context.Context, %s []runtime.Value) runtime.Result { return host.Call(ctx, %s, %s) })", callback, args, quote("__lip_fn_"+named.Name), args)
		return callback, nil
	}
	fn, ok := expr.(*ast.LambdaExpr)
	if !ok {
		return "", fmt.Errorf("callback must be a local pure function name or inline fn")
	}
	callback, args := e.temp(), e.temp()
	e.line("%s := runtime.Op(func(ctx context.Context, %s []runtime.Value) runtime.Result {", callback, args)
	body := e.child(e.indent + "\t")
	params := map[string]int{}
	for index, param := range fn.Params {
		params[param] = index
	}
	body.ident = func(name string) string {
		if index, exists := params[name]; exists {
			return fmt.Sprintf("%s[%d]", args, index)
		}
		return e.ident(name)
	}
	body.line("ctx, err := runtime.EnterFunction(ctx); if err != nil { return runtime.Failed(err) }")
	body.line("if len(%s) != %d { return runtime.Failed(fmt.Errorf(\"callback expects %d arguments, got %%d\", len(%s))) }", args, len(fn.Params), len(fn.Params), args)
	for index, param := range fn.Params {
		if typ := paramType(fn.ParamTypes, param); typ != "any" {
			body.line("if err := runtime.CheckType(%s[%d], %s); err != nil { return runtime.Failed(fmt.Errorf(\"callback argument %s: %%w\", err)) }", args, index, quote(typ), param)
		}
	}
	value, err := body.value(fn.Return)
	if err != nil {
		return "", err
	}
	resultType := fn.ReturnType
	if resultType == "" {
		resultType = fn.InferredReturnType
	}
	body.line("if err := runtime.CheckType(%s, %s); err != nil { return runtime.Failed(fmt.Errorf(\"callback result: %%w\", err)) }", value, quote(runtimeType(resultType)))
	body.line("return runtime.Ready(%s)", value)
	e.line("})")
	return callback, nil
}

func emitFunction(fn *ast.Function) (string, error) {
	params := make(map[string]int, len(fn.Params))
	for i, param := range fn.Params {
		params[param] = i
	}
	ident := func(name string) string { return fmt.Sprintf("args[%d]", params[name]) }
	var b strings.Builder
	fmt.Fprintf(&b, "func __lip_fn_%s(host runtime.Host) runtime.Op {\n", fn.Name)
	b.WriteString("\treturn func(ctx context.Context, args []runtime.Value) runtime.Result {\n\t\tctx, err := runtime.EnterFunction(ctx); if err != nil { return runtime.Failed(err) }\n")
	fmt.Fprintf(&b, "\t\tif len(args) != %d { return runtime.Failed(fmt.Errorf(\"function %s expects %d arguments, got %%d\", len(args))) }\n", len(fn.Params), fn.Name, len(fn.Params))
	for i, param := range fn.Params {
		if typ := gFunctionParamType(fn, param); typ != "any" {
			fmt.Fprintf(&b, "\t\tif err := runtime.CheckType(args[%d], %s); err != nil { return runtime.Failed(fmt.Errorf(\"argument %s: %%w\", err)) }\n", i, quote(typ), param)
		}
	}
	emitter := newValueEmitter(ident, "\t\t")
	resultType := fn.ReturnType
	if resultType == "" {
		resultType = fn.InferredReturnType
	}
	if optimized, fallback, err := emitOptimizedRecursion(fn, emitter, runtimeType(resultType)); err != nil {
		return "", fmt.Errorf("function %s: %w", fn.Name, err)
	} else if optimized {
		if fallback {
			if err := emitNormalReturn(fn.Return, emitter, fn.Name, runtimeType(resultType)); err != nil {
				return "", fmt.Errorf("function %s: %w", fn.Name, err)
			}
		}
		if code := emitter.code(); code != "" {
			b.WriteString(code)
			b.WriteString("\n")
		}
		b.WriteString("\t}\n}\n")
		return b.String(), nil
	}
	// A local call in return position is emitted as a runtime trampoline jump.
	// The same helper handles if expressions so mutually recursive functions do
	// not grow the Go stack. Non-tail expressions retain the ordinary generated
	// value path and result validation.
	if handled, err := emitTailReturn(fn.Return, emitter, fn.Name, runtimeType(resultType)); err != nil {
		return "", fmt.Errorf("function %s: %w", fn.Name, err)
	} else if !handled {
		value, err := emitter.value(fn.Return)
		if err != nil {
			return "", fmt.Errorf("function %s: %w", fn.Name, err)
		}
		if code := emitter.code(); code != "" {
			b.WriteString(code)
			b.WriteString("\n")
		}
		fmt.Fprintf(&b, "\t\tif err := runtime.CheckType(%s, %s); err != nil { return runtime.Failed(fmt.Errorf(\"function %s result: %%w\", err)) }\n", value, quote(runtimeType(resultType)), fn.Name)
		fmt.Fprintf(&b, "\t\treturn runtime.Ready(%s)\n", value)
	} else if code := emitter.code(); code != "" {
		b.WriteString(code)
		b.WriteString("\n")
	}
	b.WriteString("\t}\n}\n")
	return b.String(), nil
}

func emitNormalReturn(expr ast.Expr, emitter *valueEmitter, functionName, resultType string) error {
	value, err := emitter.value(expr)
	if err != nil {
		return err
	}
	emitter.line("if err := runtime.CheckType(%s, %s); err != nil { return runtime.Failed(fmt.Errorf(\"function %s result: %%w\", err)) }", value, quote(resultType), functionName)
	emitter.line("return runtime.Ready(%s)", value)
	return nil
}

type linearRecurrence struct {
	param   string
	condOp  string
	bound   float64
	combine string
	term    ast.Expr
	step    float64
	base    ast.Expr
}

type branchRecurrence struct {
	param               string
	condOp              string
	bound               float64
	combine             string
	leftDelta           int
	rightDelta          int
	base                ast.Expr
	decreasing          bool
	iterationStart      int
	needsIterationOp    string
	needsIterationBound float64
}

func emitOptimizedRecursion(fn *ast.Function, emitter *valueEmitter, resultType string) (bool, bool, error) {
	recurrence, ok := matchLinearRecurrence(fn)
	if ok {
		if err := emitLinearRecurrence(fn, emitter, resultType, recurrence); err != nil {
			return false, false, err
		}
		return true, false, nil
	}
	branch, ok := matchBranchRecurrence(fn)
	if !ok {
		return false, false, nil
	}
	if err := emitBranchRecurrence(fn, emitter, resultType, branch); err != nil {
		return false, false, err
	}
	return true, true, nil
}

func emitLinearRecurrence(fn *ast.Function, emitter *valueEmitter, resultType string, recurrence linearRecurrence) error {
	index := -1
	for i, name := range fn.Params {
		if name == recurrence.param {
			index = i
			break
		}
	}
	if index < 0 {
		return fmt.Errorf("recursive parameter not found")
	}
	arg := fmt.Sprintf("args[%d]", index)
	// The current value is substituted for the recursive parameter in the
	// condition, base and accumulation term. This keeps each loop iteration
	// equivalent to one recursive frame while preserving runtime arithmetic.
	emitter.line("recCurrent := %s", arg)
	recIdent := func(name string) string {
		if name == recurrence.param {
			return "recCurrent"
		}
		return emitter.ident(name)
	}
	recEmitter := &valueEmitter{lines: emitter.lines, next: emitter.next, indent: emitter.indent, ident: recIdent}
	base, err := recEmitter.value(recurrence.base)
	if err != nil {
		return err
	}
	emitter.line("recAccum := %s", base)
	emitter.line("for {")
	loop := emitter.child(emitter.indent + "\t")
	loop.line("if err := ctx.Err(); err != nil { return runtime.Failed(err) }")
	condition := loop.temp()
	loop.line("%s, err := runtime.Binary(%s, recCurrent, %s)", condition, quote(recurrence.condOp), literal(recurrence.bound))
	loop.line("if err != nil { return runtime.Failed(err) }")
	done := loop.temp()
	loop.line("%s, err := runtime.Bool(%s)", done, condition)
	loop.line("if err != nil { return runtime.Failed(err) }")
	loop.line("if %s {", done)
	finish := loop.child(loop.indent + "\t")
	finish.line("if err := runtime.CheckType(recAccum, %s); err != nil { return runtime.Failed(fmt.Errorf(\"function %s result: %%w\", err)) }", quote(resultType), fn.Name)
	finish.line("return runtime.Ready(recAccum)")
	loop.line("}")
	term, err := recEmitterWithIndent(recEmitter, loop.indent).value(recurrence.term)
	if err != nil {
		return err
	}
	loop.line("recAccum, err = runtime.Binary(%s, recAccum, %s)", quote(recurrence.combine), term)
	loop.line("if err != nil { return runtime.Failed(err) }")
	loop.line("recCurrent, err = runtime.Binary(\"+\", recCurrent, %s)", literal(recurrence.step))
	loop.line("if err != nil { return runtime.Failed(err) }")
	emitter.line("}")
	return nil
}

// emitBranchRecurrence lowers a small, name-independent dynamic recurrence
// such as f(n) = f(n-1) + f(n-2) to a bounded state table. The matcher below
// deliberately accepts only direct numeric branches, so fractional inputs and
// shapes with unknown evaluation order use the original recursive code.
func emitBranchRecurrence(fn *ast.Function, emitter *valueEmitter, resultType string, recurrence branchRecurrence) error {
	index := -1
	for i, name := range fn.Params {
		if name == recurrence.param {
			index = i
			break
		}
	}
	if index < 0 {
		return fmt.Errorf("recursive parameter not found")
	}
	arg := fmt.Sprintf("args[%d]", index)
	emitter.line("branchInteger, err := runtime.IsIntegerNumber(%s)", arg)
	emitter.line("if err != nil { return runtime.Failed(err) }")
	emitter.line("if branchInteger {")
	body := emitter.child(emitter.indent + "\t")
	body.line("branchN, err := runtime.Number(%s)", arg)
	body.line("if err != nil { return runtime.Failed(err) }")
	body.line("if branchN %s %s && %s <= float64(runtime.MaxRangeLength) {", recurrence.needsIterationOp, goNumberLiteral(recurrence.needsIterationBound), recurrenceSizeExpression(recurrence))
	loop := body.child(body.indent + "\t")
	loop.line("branchValues := map[int]runtime.Value{}")
	if recurrence.decreasing {
		loop.line("for branchI := %d; branchI <= int(branchN); branchI++ {", recurrence.iterationStart)
	} else {
		loop.line("for branchI := %d; branchI >= int(branchN); branchI-- {", recurrence.iterationStart)
	}
	iteration := loop.child(loop.indent + "\t")
	iteration.line("branchCurrent := runtime.Value(float64(branchI))")
	baseCheck := iteration.temp()
	iteration.line("%s, err := runtime.Binary(%s, branchCurrent, %s)", baseCheck, quote(recurrence.condOp), literal(recurrence.bound))
	iteration.line("if err != nil { return runtime.Failed(err) }")
	baseBool := iteration.temp()
	iteration.line("%s, err := runtime.Bool(%s)", baseBool, baseCheck)
	iteration.line("if err != nil { return runtime.Failed(err) }")
	iteration.line("if %s {", baseBool)
	baseEmitter := &valueEmitter{lines: iteration.lines, next: iteration.next, indent: iteration.indent + "\t", ident: func(name string) string {
		if name == recurrence.param {
			return "branchCurrent"
		}
		return emitter.ident(name)
	}}
	base, err := baseEmitter.value(recurrence.base)
	if err != nil {
		return err
	}
	iteration.line("branchValues[branchI] = %s", base)
	iteration.line("continue")
	iteration.line("}")
	left := iteration.temp()
	right := iteration.temp()
	iteration.line("%s, ok := branchValues[branchI+%d]", left, recurrence.leftDelta)
	iteration.line("if !ok { return runtime.Failed(fmt.Errorf(\"recurrence state missing at %%d\", branchI+%d)) }", recurrence.leftDelta)
	iteration.line("%s, ok := branchValues[branchI+%d]", right, recurrence.rightDelta)
	iteration.line("if !ok { return runtime.Failed(fmt.Errorf(\"recurrence state missing at %%d\", branchI+%d)) }", recurrence.rightDelta)
	result := iteration.temp()
	iteration.line("%s, err := runtime.Binary(%s, %s, %s)", result, quote(recurrence.combine), left, right)
	iteration.line("if err != nil { return runtime.Failed(err) }")
	iteration.line("branchValues[branchI] = %s", result)
	loop.line("}")
	branchResult := body.temp()
	body.line("%s, ok := branchValues[int(branchN)]", branchResult)
	body.line("if !ok { return runtime.Failed(fmt.Errorf(\"recurrence result missing\")) }")
	body.line("if err := runtime.CheckType(%s, %s); err != nil { return runtime.Failed(fmt.Errorf(\"function %s result: %%w\", err)) }", branchResult, quote(resultType), fn.Name)
	body.line("return runtime.Ready(%s)", branchResult)
	body.line("}")
	emitter.line("}")
	return nil
}

func goNumberLiteral(value float64) string {
	return strconv.FormatFloat(value, 'g', -1, 64)
}

func recEmitterWithIndent(base *valueEmitter, indent string) *valueEmitter {
	return &valueEmitter{lines: base.lines, next: base.next, indent: indent, ident: base.ident}
}

type boundCondition struct {
	op    string
	bound float64
}

func normalizedBound(expr ast.Expr, param string) (boundCondition, bool) {
	binary, ok := expr.(*ast.BinaryExpr)
	if !ok {
		return boundCondition{}, false
	}
	if left, ok := binary.Left.(*ast.IdentExpr); ok && left.Name == param {
		if bound, ok := numericLiteral(binary.Right); ok {
			return boundCondition{op: binary.Op, bound: bound}, binary.Op == "<=" || binary.Op == "<" || binary.Op == ">=" || binary.Op == ">"
		}
	}
	if right, ok := binary.Right.(*ast.IdentExpr); ok && right.Name == param {
		if bound, ok := numericLiteral(binary.Left); ok {
			op := reverseComparison(binary.Op)
			return boundCondition{op: op, bound: bound}, op == "<=" || op == "<" || op == ">=" || op == ">"
		}
	}
	return boundCondition{}, false
}

func reverseComparison(op string) string {
	switch op {
	case "<":
		return ">"
	case "<=":
		return ">="
	case ">":
		return "<"
	case ">=":
		return "<="
	default:
		return op
	}
}

func matchLinearRecurrence(fn *ast.Function) (linearRecurrence, bool) {
	if len(fn.Params) != 1 {
		return linearRecurrence{}, false
	}
	condition, ok := fn.Return.(*ast.IfExpr)
	if !ok {
		return linearRecurrence{}, false
	}
	bound, ok := normalizedBound(condition.Cond, fn.Params[0])
	if !ok {
		return linearRecurrence{}, false
	}
	stepCall := findRecursiveCall(condition.Else, fn.Name)
	if stepCall == nil || containsCallNamed(condition.Then, fn.Name) {
		return linearRecurrence{}, false
	}
	step, ok := recursiveStep(stepCall.Args[0], fn.Params[0])
	if !ok || step == 0 || hasWrongDirection(bound.op, step) {
		return linearRecurrence{}, false
	}
	combine, ok := condition.Else.(*ast.BinaryExpr)
	if !ok || (combine.Op != "+" && combine.Op != "*") {
		return linearRecurrence{}, false
	}
	var term ast.Expr
	if containsCallNamed(combine.Left, fn.Name) {
		leftCall, leftOK := combine.Left.(*ast.CallExpr)
		if !leftOK || !sameRecursiveCall(leftCall, stepCall) || containsCallNamed(combine.Right, fn.Name) {
			return linearRecurrence{}, false
		}
		term = combine.Right
	} else if containsCallNamed(combine.Right, fn.Name) {
		rightCall, rightOK := combine.Right.(*ast.CallExpr)
		if !rightOK || !sameRecursiveCall(rightCall, stepCall) || containsCallNamed(combine.Left, fn.Name) {
			return linearRecurrence{}, false
		}
		term = combine.Left
	} else {
		return linearRecurrence{}, false
	}
	if containsAnyCall(term) || containsAnyCall(condition.Then) {
		return linearRecurrence{}, false
	}
	return linearRecurrence{param: fn.Params[0], condOp: bound.op, bound: bound.bound, combine: combine.Op, term: term, step: step, base: condition.Then}, true
}

func matchBranchRecurrence(fn *ast.Function) (branchRecurrence, bool) {
	if len(fn.Params) != 1 {
		return branchRecurrence{}, false
	}
	condition, ok := fn.Return.(*ast.IfExpr)
	if !ok {
		return branchRecurrence{}, false
	}
	bound, ok := normalizedBound(condition.Cond, fn.Params[0])
	if !ok || !integerLiteral(bound.bound) || containsAnyCall(condition.Then) {
		return branchRecurrence{}, false
	}
	combine, ok := condition.Else.(*ast.BinaryExpr)
	if !ok || (combine.Op != "+" && combine.Op != "-" && combine.Op != "*" && combine.Op != "/") {
		return branchRecurrence{}, false
	}
	left, lok := directRecursiveStep(combine.Left, fn.Name, fn.Params[0])
	right, rok := directRecursiveStep(combine.Right, fn.Name, fn.Params[0])
	if !lok || !rok || left == 0 || right == 0 || !integerLiteral(left) || !integerLiteral(right) {
		return branchRecurrence{}, false
	}
	decreasing := bound.op == "<" || bound.op == "<="
	increasing := bound.op == ">" || bound.op == ">="
	if !decreasing && !increasing || decreasing && (left >= 0 || right >= 0) || increasing && (left <= 0 || right <= 0) {
		return branchRecurrence{}, false
	}
	minStep, maxStep := left, left
	if right < minStep {
		minStep = right
	}
	if right > maxStep {
		maxStep = right
	}
	if math.Abs(bound.bound) > float64(runtime.MaxRangeLength) || math.Abs(float64(minStep)) > runtime.MaxRangeLength || math.Abs(float64(maxStep)) > runtime.MaxRangeLength {
		return branchRecurrence{}, false
	}
	start := 0
	needsBound := bound.bound
	if decreasing {
		baseMax := int(bound.bound)
		if bound.op == "<" {
			baseMax--
		}
		start = baseMax + int(minStep)
	} else {
		baseMin := int(bound.bound)
		if bound.op == ">" {
			baseMin++
		}
		start = baseMin + int(maxStep) - 1
	}
	return branchRecurrence{
		param:               fn.Params[0],
		condOp:              bound.op,
		bound:               bound.bound,
		combine:             combine.Op,
		leftDelta:           int(left),
		rightDelta:          int(right),
		base:                condition.Then,
		decreasing:          decreasing,
		iterationStart:      start,
		needsIterationOp:    iterationGuardOp(bound.op),
		needsIterationBound: needsBound,
	}, true
}

func iterationGuardOp(conditionOp string) string {
	switch conditionOp {
	case "<":
		return ">="
	case "<=":
		return ">"
	case ">":
		return "<="
	case ">=":
		return "<"
	default:
		return ">="
	}
}

func recurrenceSizeExpression(recurrence branchRecurrence) string {
	if recurrence.decreasing {
		return fmt.Sprintf("branchN-float64(%d)", recurrence.iterationStart)
	}
	return fmt.Sprintf("float64(%d)-branchN", recurrence.iterationStart)
}

func directRecursiveStep(expr ast.Expr, name, param string) (float64, bool) {
	call, ok := expr.(*ast.CallExpr)
	if !ok || !call.Local || call.Name != name || len(call.Args) != 1 {
		return 0, false
	}
	return recursiveStep(call.Args[0], param)
}

func integerLiteral(value float64) bool {
	return !math.IsNaN(value) && !math.IsInf(value, 0) && value == math.Trunc(value)
}

func findRecursiveCall(expr ast.Expr, name string) *ast.CallExpr {
	var found *ast.CallExpr
	visitCalls(expr, func(call *ast.CallExpr) {
		if found == nil && call.Local && call.Name == name {
			found = call
		}
	})
	return found
}

func sameRecursiveCall(a, b *ast.CallExpr) bool {
	if a == nil || b == nil || len(a.Args) != 1 || len(b.Args) != 1 {
		return false
	}
	leftA, okA := a.Args[0].(*ast.BinaryExpr)
	leftB, okB := b.Args[0].(*ast.BinaryExpr)
	if !okA || !okB || leftA.Op != leftB.Op {
		return false
	}
	paramA, okA := leftA.Left.(*ast.IdentExpr)
	paramB, okB := leftB.Left.(*ast.IdentExpr)
	if !okA || !okB || paramA.Name != paramB.Name {
		return false
	}
	boundA, okA := numericLiteral(leftA.Right)
	boundB, okB := numericLiteral(leftB.Right)
	return a.Local == b.Local && a.Name == b.Name && okA && okB && boundA == boundB
}

func recursiveStep(expr ast.Expr, param string) (float64, bool) {
	binary, ok := expr.(*ast.BinaryExpr)
	if !ok {
		return 0, false
	}
	left, ok := binary.Left.(*ast.IdentExpr)
	if !ok || left.Name != param {
		return 0, false
	}
	right, ok := numericLiteral(binary.Right)
	if !ok {
		return 0, false
	}
	if binary.Op == "-" {
		return -right, true
	}
	if binary.Op == "+" {
		return right, true
	}
	return 0, false
}

func numericLiteral(expr ast.Expr) (float64, bool) {
	literal, ok := expr.(*ast.LiteralExpr)
	if !ok {
		return 0, false
	}
	value, ok := literal.Value.(float64)
	return value, ok
}

func hasWrongDirection(op string, step float64) bool {
	if (op == "<=" || op == "<") && step >= 0 {
		return true
	}
	if (op == ">=" || op == ">") && step <= 0 {
		return true
	}
	return false
}

func containsCallNamed(expr ast.Expr, name string) bool {
	found := false
	visitCalls(expr, func(call *ast.CallExpr) {
		if call.Local && call.Name == name {
			found = true
		}
	})
	return found
}

func containsAnyCall(expr ast.Expr) bool {
	found := false
	visitCalls(expr, func(*ast.CallExpr) { found = true })
	return found
}

// emitTailReturn emits a return expression directly when every possible
// branch ends in a local call in tail position. It returns handled=true when
// it wrote all returns. Branches that are not tail calls still return through
// the normal runtime type check, preserving the function's error semantics.
func emitTailReturn(expr ast.Expr, emitter *valueEmitter, functionName, resultType string) (bool, error) {
	switch x := expr.(type) {
	case *ast.CallExpr:
		if !x.Local {
			return false, nil
		}
		args := make([]string, len(x.Args))
		for i, arg := range x.Args {
			value, err := emitter.value(arg)
			if err != nil {
				return false, err
			}
			args[i] = value
		}
		emitter.line("return runtime.TailCall(%s, []runtime.Value{%s}, %s)", quote(dispatchName(x)), strings.Join(args, ", "), quote(resultType))
		return true, nil
	case *ast.IfExpr:
		cond, err := emitter.value(x.Cond)
		if err != nil {
			return false, err
		}
		condition := emitter.temp()
		emitter.line("%s, err := runtime.Bool(%s)", condition, cond)
		emitter.line("if err != nil { return runtime.Failed(err) }")
		emitter.line("if %s {", condition)
		thenEmitter := emitter.child(emitter.indent + "\t")
		thenHandled, err := emitTailBranch(x.Then, thenEmitter, functionName, resultType)
		if err != nil {
			return false, err
		}
		emitter.line("} else {")
		elseEmitter := emitter.child(emitter.indent + "\t")
		elseHandled, err := emitTailBranch(x.Else, elseEmitter, functionName, resultType)
		if err != nil {
			return false, err
		}
		emitter.line("}")
		return thenHandled || elseHandled, nil
	case *ast.MatchExpr:
		return emitTailMatchReturn(x, emitter, functionName, resultType)
	default:
		return false, nil
	}
}

func emitTailMatchReturn(expr *ast.MatchExpr, emitter *valueEmitter, functionName, resultType string) (bool, error) {
	scrutinee, err := emitter.value(expr.Value)
	if err != nil {
		return false, err
	}
	emitter.line("_ = %s", scrutinee)
	matched := emitter.temp()
	emitter.line("%s := false", matched)
	for _, arm := range expr.Arms {
		emitter.line("if !%s {", matched)
		branch := emitter.child(emitter.indent + "\t")
		patterns := matchPatterns(arm)
		typePatterns := matchTypePatterns(arm)
		if len(patterns) > 0 || len(typePatterns) > 0 {
			patternMatched := branch.temp()
			branch.line("%s := false", patternMatched)
			for _, pattern := range patterns {
				comparison := branch.temp()
				branch.line("%s, err := runtime.Binary(\"==\", %s, %s)", comparison, scrutinee, literal(pattern.Value))
				branch.line("if err != nil { return runtime.Failed(err) }")
				condition := branch.temp()
				branch.line("%s, err := runtime.Bool(%s)", condition, comparison)
				branch.line("if err != nil { return runtime.Failed(err) }")
				branch.line("if %s { %s = true }", condition, patternMatched)
			}
			for _, patternType := range typePatterns {
				condition := branch.temp()
				branch.line("%s := runtime.IsType(%s, %s)", condition, scrutinee, quote(patternType))
				branch.line("if %s { %s = true }", condition, patternMatched)
			}
			branch.line("if %s {", patternMatched)
			branch = branch.child(branch.indent + "\t")
		}
		if arm.Guard != nil {
			guard, err := branch.value(arm.Guard)
			if err != nil {
				return false, err
			}
			condition := branch.temp()
			branch.line("%s, err := runtime.Bool(%s)", condition, guard)
			branch.line("if err != nil { return runtime.Failed(err) }")
			branch.line("if %s {", condition)
			branch = branch.child(branch.indent + "\t")
		}
		branch.line("%s = true", matched)
		if _, err := emitTailBranch(arm.Expr, branch, functionName, resultType); err != nil {
			return false, err
		}
		if arm.Guard != nil {
			emitter.line("}")
		}
		if len(patterns) > 0 || len(typePatterns) > 0 {
			emitter.line("}")
		}
		emitter.line("}")
	}
	emitter.line("if !%s { return runtime.Failed(fmt.Errorf(\"non-exhaustive match\")) }", matched)
	// Go cannot prove that every arm above returns after the generated guards;
	// this fallback is unreachable for a validated exhaustive match but keeps
	// the generated function total if malformed data reaches it.
	emitter.line("return runtime.Failed(fmt.Errorf(\"non-exhaustive match\"))")
	return true, nil
}

func emitTailBranch(expr ast.Expr, emitter *valueEmitter, functionName, resultType string) (bool, error) {
	if handled, err := emitTailReturn(expr, emitter, functionName, resultType); handled || err != nil {
		return handled, err
	}
	value, err := emitter.value(expr)
	if err != nil {
		return false, err
	}
	emitter.line("if err := runtime.CheckType(%s, %s); err != nil { return runtime.Failed(fmt.Errorf(\"function %s result: %%w\", err)) }", value, quote(resultType), functionName)
	emitter.line("return runtime.Ready(%s)", value)
	return true, nil
}

func visitCalls(expr ast.Expr, visit func(*ast.CallExpr)) {
	switch x := expr.(type) {
	case *ast.CallExpr:
		visit(x)
		for _, arg := range x.Args {
			visitCalls(arg, visit)
		}
	case *ast.UnaryExpr:
		visitCalls(x.Operand, visit)
	case *ast.LambdaExpr:
		visitCalls(x.Return, visit)
	case *ast.ObjectExpr:
		for _, field := range x.Fields {
			visitCalls(field.Value, visit)
		}
	case *ast.BinaryExpr:
		visitCalls(x.Left, visit)
		visitCalls(x.Right, visit)
	case *ast.IfExpr:
		visitCalls(x.Cond, visit)
		visitCalls(x.Then, visit)
		visitCalls(x.Else, visit)
	case *ast.MatchExpr:
		for _, part := range matchParts(x) {
			visitCalls(part, visit)
		}
	case *ast.ListExpr:
		for _, item := range x.Items {
			visitCalls(item, visit)
		}
	case *ast.ComprehensionExpr:
		visitCalls(x.Element, visit)
		visitCalls(x.Source, visit)
	case *ast.FieldExpr:
		visitCalls(x.Object, visit)
	case *ast.IndexExpr:
		visitCalls(x.Object, visit)
		visitCalls(x.Index, visit)
	}
}

func firstPythonCall(expr ast.Expr) *ast.CallExpr {
	var result *ast.CallExpr
	visitCalls(expr, func(call *ast.CallExpr) {
		if (call.Python || !call.Host && isPythonControlOperation(call.Name)) && result == nil {
			result = call
		}
	})
	return result
}

func firstExternalCall(expr ast.Expr) *ast.CallExpr {
	var result *ast.CallExpr
	visitCalls(expr, func(call *ast.CallExpr) {
		if externalCall(call) && result == nil {
			result = call
		}
	})
	return result
}

func callNames(expr ast.Expr) []string {
	seen := map[string]bool{}
	var names []string
	add := func(name string) {
		if !seen[name] {
			seen[name] = true
			names = append(names, name)
		}
	}
	visitCalls(expr, func(call *ast.CallExpr) {
		add(call.Name)
		if index := callbackIndex(call); index >= 0 {
			if reducer, ok := call.Args[index].(*ast.IdentExpr); ok {
				add(reducer.Name)
			}
		}
	})
	return names
}

func literal(v any) string {
	switch x := v.(type) {
	case string:
		return "runtime.Value(" + quote(x) + ")"
	case bool:
		if x {
			return "runtime.Value(true)"
		}
		return "runtime.Value(false)"
	case float64:
		return fmt.Sprintf("runtime.Value(float64(%s))", strconv.FormatFloat(x, 'g', -1, 64))
	default:
		return "runtime.Value(nil)"
	}
}

func stringSlice(values []string) string {
	if len(values) == 0 {
		return "nil"
	}
	parts := make([]string, len(values))
	for i, v := range values {
		parts[i] = quote(v)
	}
	return "[]string{" + strings.Join(parts, ", ") + "}"
}

func quote(s string) string { return strconv.Quote(s) }

func gParamType(g *Graph, name string) string {
	if g.ParamTypes != nil {
		if typ := g.ParamTypes[name]; typ != "" {
			return typ
		}
	}
	return "any"
}

func gFunctionParamType(fn *ast.Function, name string) string {
	if fn.ParamTypes != nil {
		if typ := fn.ParamTypes[name]; typ != "" {
			return typ
		}
	}
	return "any"
}

func runtimeType(typ string) string {
	if validOutputType(typ) {
		return typ
	}
	return "any"
}

func generatedEffect(expr ast.Expr, functions []*ast.Function) string {
	random := false
	visitCalls(expr, func(call *ast.CallExpr) {
		if !externalCall(call) && randomBuiltinName(call.Name) {
			random = true
		}
	})
	if random {
		return "runtime.EffectExternalWrite"
	}
	operations := effectOperations(expr, functions)
	if len(operations) == 0 {
		return "runtime.EffectPure"
	}
	return "host.EffectsOf(" + stringSlice(operations) + ")"
}

func effectOperations(expr ast.Expr, functions []*ast.Function) []string {
	var operations []string
	visitCalls(expr, func(call *ast.CallExpr) {
		if call.PythonAttribute {
			operations = append(operations, "python.getattr")
			return
		}
		if !externalCall(call) {
			if pureBuiltinName(call.Name) || call.Name == "state" || call.Name == "retry" || call.Name == "feedback" {
				return
			}
			for _, fn := range functions {
				if fn.Name == call.Name {
					return
				}
			}
		}
		operations = append(operations, call.Name)
	})
	return unique(operations)
}

func feedbackOperation(call *ast.CallExpr, index int) *ast.CallExpr {
	ref := call.Args[index].(*ast.IdentExpr)
	return &ast.CallExpr{Name: ref.Name, Local: ref.OperationKind == "fn", Python: ref.OperationKind == "python", Host: ref.OperationKind == "host" || ref.OperationKind == "go", Args: []ast.Expr{&ast.IdentExpr{Name: "__lip_feedback_current"}}}
}

func pureExpression(expr ast.Expr, functions []*ast.Function) bool {
	if firstExternalCall(expr) != nil {
		return false
	}
	for _, called := range callNames(expr) {
		if pureBuiltinName(called) {
			continue
		}
		found := false
		for _, fn := range functions {
			if fn.Name == called {
				found = true
				break
			}
		}
		if !found {
			return false
		}
	}
	return true
}

func requiredHostOperations(g *Graph) []string {
	var operations []string
	var hostCalls []string
	var collect func(*Graph)
	collect = func(graph *Graph) {
		for _, node := range graph.Nodes {
			actual := effectOperations(node.Expr, graph.Functions)
			visitCalls(node.Expr, func(call *ast.CallExpr) {
				if !call.Python && containsOperation(actual, call.Name) {
					hostCalls = append(hostCalls, call.Name)
				}
			})
			if node.FeedbackAttempts > 0 {
				call := node.Expr.(*ast.CallExpr)
				for _, index := range []int{1, 2} {
					op := feedbackOperation(call, index)
					if !op.Python && len(effectOperations(op, graph.Functions)) > 0 {
						hostCalls = append(hostCalls, op.Name)
					}
				}
			}
			if node.For != nil {
				collect(node.For.Body)
			}
		}
	}
	collect(g)
	for _, dependency := range g.Dependencies {
		if dependency.Kind == "go" {
			for _, operation := range hostCalls {
				if strings.HasPrefix(operation, dependency.Spec+".") {
					operations = append(operations, operation)
				}
			}
			continue
		}
		if dependency.Kind != "host" {
			continue
		}
		if !strings.HasSuffix(dependency.Spec, ".*") {
			if containsOperation(hostCalls, dependency.Spec) {
				operations = append(operations, dependency.Spec)
			}
			continue
		}
		prefix := strings.TrimSuffix(dependency.Spec, "*")
		for _, operation := range hostCalls {
			if strings.HasPrefix(operation, prefix) {
				operations = append(operations, operation)
			}
		}
	}
	return unique(operations)
}

func containsOperation(operations []string, name string) bool {
	for _, operation := range operations {
		if operation == name {
			return true
		}
	}
	return false
}

// emitGraphFunction shares normal node generation with iteration bodies.
func emitGraphFunction(g *Graph, name string, b *strings.Builder) error {
	for index, node := range g.Nodes {
		if node.For != nil {
			if err := emitGraphFunction(node.For.Body, name+"_for_"+strconv.Itoa(index), b); err != nil {
				return err
			}
		}
	}
	fmt.Fprintf(b, "func %s(host runtime.Host) *runtime.Graph {\n\thost = host.Clone()\n\tg := runtime.NewGraphWithOptions(runtime.GraphOptions{ReleaseIntermediates: true})\n", name)
	for _, fn := range g.Functions {
		fmt.Fprintf(b, "\thost.RegisterPure(%s, __lip_fn_%s(host))\n", quote("__lip_fn_"+fn.Name), fn.Name)
	}
	for index, n := range g.Nodes {
		if n.For != nil {
			if err := emitForNode(n, name+"_for_"+strconv.Itoa(index), b); err != nil {
				return err
			}
			continue
		}
		if n.LoopControl != "" {
			emitLoopControl(n, b)
			continue
		}
		if n.FeedbackAttempts > 0 {
			call, ok := n.Expr.(*ast.CallExpr)
			if !ok || len(call.Args) != 4 {
				return fmt.Errorf("node %s: invalid feedback expression", n.Name)
			}
			initial, ok := call.Args[0].(*ast.CallExpr)
			if !ok {
				return fmt.Errorf("node %s: feedback initial expression must be a call", n.Name)
			}
			step, verify := feedbackOperation(call, 1), feedbackOperation(call, 2)
			ops := append(effectOperations(initial, g.Functions), effectOperations(step, g.Functions)...)
			ops = append(ops, effectOperations(verify, g.Functions)...)
			fmt.Fprintf(b, "\tg.Add(runtime.NodeSpec{Name: %s, Effect: host.EffectsOf(%s), Deps: %s, Gates: %s, Feedback: &runtime.FeedbackSpec{Attempts: %d, Init: func(ctx context.Context, values map[string]runtime.Value) runtime.Result {\n", quote(n.Name), stringSlice(unique(ops)), stringSlice(n.Deps), stringSlice(n.Gates), n.FeedbackAttempts)
			expr, err := emitExpr(initial)
			if err != nil {
				return fmt.Errorf("node %s: %w", n.Name, err)
			}
			b.WriteString(expr)
			for index, operation := range []*ast.CallExpr{step, verify} {
				field := "Step"
				if index == 1 {
					field = "Verify"
				}
				fmt.Fprintf(b, "\n\t}, %s: func(ctx context.Context, current runtime.Value) runtime.Result {\n", field)
				body, err := emitResultExpr(operation, newValueEmitter(func(string) string { return "current" }, "\t\t"))
				if err != nil {
					return err
				}
				b.WriteString(body)
			}
			b.WriteString("\n\t}},")
			if len(n.Gates) > 0 {
				b.WriteString(" Gate: func(values map[string]runtime.Value) (bool, error) {\n")
				for gateIndex, gate := range n.Gates {
					fmt.Fprintf(b, "\t\tok%d, err := runtime.Bool(values[%s]); if err != nil { return false, err }; if !ok%d { return false, nil }\n", gateIndex, quote(gate), gateIndex)
				}
				b.WriteString("\t\treturn true, nil\n\t},")
			}
			if n.Output {
				fmt.Fprintf(b, " Output: true, ValueType: %s,", quote(g.ReturnType))
			}
			b.WriteString("})\n")
			continue
		}
		if n.RetryAttempts > 0 {
			call, ok := n.Expr.(*ast.CallExpr)
			if !ok || len(call.Args) != 2 {
				return fmt.Errorf("node %s: invalid retry expression", n.Name)
			}
			inner, ok := call.Args[0].(*ast.CallExpr)
			if !ok {
				return fmt.Errorf("node %s: retry first argument must be a call", n.Name)
			}
			fmt.Fprintf(b, "\tg.Add(runtime.NodeSpec{Name: %s, Op: %s, Effect: %s, Deps: %s, Gates: %s, Retry: &runtime.RetrySpec{Attempts: %d, Eval: func(ctx context.Context, values map[string]runtime.Value) runtime.Result {\n", quote(n.Name), quote(inner.Name), generatedEffect(inner, g.Functions), stringSlice(n.Deps), stringSlice(n.Gates), n.RetryAttempts)
			expr, err := emitExpr(inner)
			if err != nil {
				return fmt.Errorf("node %s: %w", n.Name, err)
			}
			b.WriteString(expr)
			b.WriteString("\n\t}},")
			if len(n.Gates) > 0 {
				b.WriteString(" Gate: func(values map[string]runtime.Value) (bool, error) {\n")
				for gateIndex, gate := range n.Gates {
					fmt.Fprintf(b, "\t\tok%d, err := runtime.Bool(values[%s]); if err != nil { return false, err }; if !ok%d { return false, nil }\n", gateIndex, quote(gate), gateIndex)
				}
				b.WriteString("\t\treturn true, nil\n\t},")
			}
			if n.Output {
				fmt.Fprintf(b, " Output: true, ValueType: %s,", quote(g.ReturnType))
			}
			b.WriteString("})\n")
			continue
		}
		if n.State {
			call, ok := n.Expr.(*ast.CallExpr)
			if !ok || len(call.Args) != 1 {
				return fmt.Errorf("node %s: invalid state expression", n.Name)
			}
			fmt.Fprintf(b, "\tg.Add(runtime.NodeSpec{Name: %s, Effect: %s, State: true, ValueType: %s, Deps: %s, Gates: %s, Eval: func(ctx context.Context, values map[string]runtime.Value) runtime.Result {\n", quote(n.Name), generatedEffect(call.Args[0], g.Functions), quote(runtimeType(n.Type)), stringSlice(n.Deps), stringSlice(n.Gates))
			expr, err := emitExpr(call.Args[0])
			if err != nil {
				return fmt.Errorf("node %s: %w", n.Name, err)
			}
			b.WriteString(expr)
			b.WriteString("\n\t},")
			if len(n.Gates) > 0 {
				b.WriteString(" Gate: func(values map[string]runtime.Value) (bool, error) {\n")
				for gateIndex, gate := range n.Gates {
					fmt.Fprintf(b, "\t\tok%d, err := runtime.Bool(values[%s]); if err != nil { return false, err }; if !ok%d { return false, nil }\n", gateIndex, quote(gate), gateIndex)
				}
				b.WriteString("\t\treturn true, nil\n\t},")
			}
			if n.Output {
				fmt.Fprintf(b, " Output: true, ValueType: %s,", quote(g.ReturnType))
			}
			b.WriteString("})\n")
			continue
		}
		if comp, ok := n.Expr.(*ast.ComprehensionExpr); ok {
			ops := callNames(comp.Element)
			effect := generatedEffect(comp, g.Functions)
			fmt.Fprintf(b, "\tg.Add(runtime.NodeSpec{Name: %s, Effect: %s, Deps: %s, Gates: %s, Map: &runtime.MapSpec{", quote(n.Name), effect, stringSlice(n.Deps), stringSlice(n.Gates))
			if source, ok := comp.Source.(*ast.IdentExpr); ok {
				fmt.Fprintf(b, "Source: %s,", quote(source.Name))
			} else {
				b.WriteString("SourceEval: func(ctx context.Context, values map[string]runtime.Value) runtime.Result {\n")
				source, err := emitExpr(comp.Source)
				if err != nil {
					return fmt.Errorf("node %s: comprehension source: %w", n.Name, err)
				}
				b.WriteString(source)
				b.WriteString("\n\t\t},")
			}
			fmt.Fprintf(b, " Ops: %s, Eval: func(ctx context.Context, item runtime.Value, values map[string]runtime.Value) runtime.Result {\n", stringSlice(ops))
			expr, err := emitMapElement(comp)
			if err != nil {
				return fmt.Errorf("node %s: %w", n.Name, err)
			}
			b.WriteString(expr)
			b.WriteString("\n\t}},")
			if len(n.Gates) > 0 {
				b.WriteString(" Gate: func(values map[string]runtime.Value) (bool, error) {\n")
				for gateIndex, gate := range n.Gates {
					fmt.Fprintf(b, "\t\tok%d, err := runtime.Bool(values[%s]); if err != nil { return false, err }; if !ok%d { return false, nil }\n", gateIndex, quote(gate), gateIndex)
				}
				b.WriteString("\t\treturn true, nil\n\t},")
			}
			if n.Output {
				fmt.Fprintf(b, " Output: true, ValueType: %s,", quote(g.ReturnType))
			}
			b.WriteString("})\n")
			continue
		}
		callName := ""
		effect := generatedEffect(n.Expr, g.Functions)
		if call, ok := n.Expr.(*ast.CallExpr); ok {
			callName = call.Name
		}
		fmt.Fprintf(b, "\tg.Add(runtime.NodeSpec{Name: %s, Op: %s, Effect: %s, Deps: %s, Gates: %s, Eval: func(ctx context.Context, values map[string]runtime.Value) runtime.Result {\n", quote(n.Name), quote(callName), effect, stringSlice(n.Deps), stringSlice(n.Gates))
		expr, err := emitExpr(n.Expr)
		if err != nil {
			return fmt.Errorf("node %s: %w", n.Name, err)
		}
		b.WriteString(expr)
		b.WriteString("\n\t},")
		if len(n.Gates) > 0 {
			b.WriteString(" Gate: func(values map[string]runtime.Value) (bool, error) {\n")
			for gateIndex, gate := range n.Gates {
				fmt.Fprintf(b, "\t\tok%d, err := runtime.Bool(values[%s]); if err != nil { return false, err }; if !ok%d { return false, nil }\n", gateIndex, quote(gate), gateIndex)
			}
			b.WriteString("\t\treturn true, nil\n\t},")
		}
		if n.Output {
			fmt.Fprintf(b, " Output: true, ValueType: %s,", quote(g.ReturnType))
		}
		b.WriteString("})\n")
	}
	b.WriteString("\treturn g\n}\n\n")
	return nil
}
